#!/usr/bin/env bash
# Undo `just dev-local`: remove the generated .cargo/config.toml and restore
# Cargo.lock from git. Refuses a config.toml it did not generate.
# usage: dev-local-off.sh [project dir]
set -euo pipefail
top=${1:-$(git rev-parse --show-toplevel)}
cfg="$top/.cargo/config.toml"
marker="# generated by just dev-local"
if [ ! -e "$cfg" ]; then
  echo "dev-local-off: nothing to do: $cfg does not exist"
  exit 0
fi
if [ "$(head -1 "$cfg")" != "$marker" ]; then
  echo "dev-local-off: $cfg was not generated by just dev-local; not removing it" >&2
  exit 1
fi
rm "$cfg"
git -C "$top" checkout -- Cargo.lock
echo "dev-local-off: removed $cfg and restored Cargo.lock from git"
