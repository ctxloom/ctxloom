#!/usr/bin/env bash
# Self-test of dev-local.py (generate .cargo/config.toml) and dev-local-off.sh
# against fixture trees: sibling checkouts, a project with a Cargo.lock.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
on="$here/dev-local.py"
off="$here/dev-local-off.sh"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
fail() { echo "selftest FAIL: $*" >&2; exit 1; }

crate() { # root-relative dir, package name
  mkdir -p "$work/root/$1"
  printf '[package]\nname = "%s"\nversion = "0.1.0"\n' "$2" > "$work/root/$1/Cargo.toml"
}
lock_pkg() { # name, source
  printf '[[package]]\nname = "%s"\nversion = "0.1.0"\n' "$1"
  [ -n "${2:-}" ] && printf 'source = "%s"\n' "$2"
  printf '\n'
}
project() { # dir
  local d="$work/$1"
  mkdir -p "$d/.cargo"
  git -C "$d" init -q 2>/dev/null || git init -q "$d"
  {
    echo 'version = 4'; echo
    lock_pkg ctxloom-fake
    lock_pkg angzarr-diagnostic 'git+https://github.com/angzarr-io/angzarr?rev=abc#abc'
    lock_pkg angzarr-yaml 'git+https://github.com/angzarr-io/angzarr?rev=abc#abc'
    lock_pkg cli-support 'git+https://github.com/ctxloom/ctxloom-lib?rev=def#def'
    lock_pkg serde 'registry+https://github.com/rust-lang/crates.io-index'
  } > "$d/Cargo.lock"
  git -C "$d" add Cargo.lock
  git -C "$d" -c user.name=t -c user.email=t@t commit -qm init
}

# Siblings: angzarr at angzarr/core/main (two crates in a workspace, a stray
# copy under worktrees/ and target/ that must be ignored), ctxloom-lib beside
# ctxloom/.
crate angzarr/core/main/crates/diag angzarr-diagnostic
crate angzarr/core/main/crates/yaml angzarr-yaml
crate angzarr/core/main/worktrees/old/crates/diag angzarr-diagnostic
crate angzarr/core/main/target/x angzarr-yaml
crate ctxloom/ctxloom-lib/crates/cs cli-support
project p1

out=$(python3 -I "$on" --project "$work/p1" "$work/root" 2>&1) || fail "generate: $out"
cfg="$work/p1/.cargo/config.toml"
[ -f "$cfg" ] || fail "no config written"
[ "$(head -1 "$cfg")" = "# generated by just dev-local" ] || fail "first line is not the marker"
grep -qF '[patch."https://github.com/angzarr-io/angzarr"]' "$cfg" || fail "no angzarr table"
grep -qF "angzarr-diagnostic = { path = \"$work/root/angzarr/core/main/crates/diag\" }" "$cfg" || fail "diagnostic path"
grep -qF "angzarr-yaml = { path = \"$work/root/angzarr/core/main/crates/yaml\" }" "$cfg" || fail "yaml path"
grep -qF "cli-support = { path = \"$work/root/ctxloom/ctxloom-lib/crates/cs\" }" "$cfg" || fail "cli-support path"
grep -q 'serde' "$cfg" && fail "a registry crate was patched"
grep -q 'ctxloom-fake' "$cfg" && fail "a workspace crate was patched"
echo "$out" | grep -q 'angzarr-diagnostic' || fail "output does not name the patched crates: $out"

# Regenerating over its own output is fine.
python3 -I "$on" --project "$work/p1" "$work/root" >/dev/null 2>&1 || fail "regenerate over own output"

# A missing crate fails, names the crate, and writes nothing.
project p2
printf '%s\n' '[[package]]' 'name = "ghost-crate"' 'version = "0.1.0"' \
  'source = "git+https://github.com/angzarr-io/angzarr?rev=abc#abc"' >> "$work/p2/Cargo.lock"
rc=0; out=$(python3 -I "$on" --project "$work/p2" "$work/root" 2>&1) || rc=$?
[ "$rc" = 1 ] || fail "missing crate: exit $rc"
echo "$out" | grep -q 'ghost-crate' || fail "missing crate not named: $out"
[ ! -e "$work/p2/.cargo/config.toml" ] || fail "config written despite a missing crate"

# An unknown checkout location is named with its override variable.
project p3
printf '%s\n' '[[package]]' 'name = "zz"' 'version = "0.1.0"' \
  'source = "git+https://github.com/some-org/elsewhere?rev=abc#abc"' >> "$work/p3/Cargo.lock"
rc=0; out=$(python3 -I "$on" --project "$work/p3" "$work/root" 2>&1) || rc=$?
[ "$rc" = 1 ] || fail "no checkout: exit $rc"
echo "$out" | grep -q 'DEV_LOCAL_ELSEWHERE' || fail "override variable not named: $out"

# The override variable points at a checkout outside the default places.
project p4
mkdir -p "$work/elsewhere"
printf '[package]\nname = "zz"\nversion = "0.1.0"\n' > "$work/elsewhere/Cargo.toml"
DEV_LOCAL_ELSEWHERE="$work/elsewhere" python3 -I "$on" --project "$work/p3" "$work/root" >/dev/null 2>&1 \
  || fail "override variable not honoured"
grep -qF "zz = { path = \"$work/elsewhere\" }" "$work/p3/.cargo/config.toml" || fail "override path"

# A config.toml it did not generate is never overwritten.
project p5
printf '[build]\njobs = 2\n' > "$work/p5/.cargo/config.toml"
rc=0; python3 -I "$on" --project "$work/p5" "$work/root" >/dev/null 2>&1 || rc=$?
[ "$rc" = 1 ] || fail "foreign config overwritten (exit $rc)"
grep -q 'jobs = 2' "$work/p5/.cargo/config.toml" || fail "foreign config changed"

# off: removes the generated config and restores Cargo.lock.
echo '# cargo rewrote me' >> "$work/p1/Cargo.lock"
out=$("$off" "$work/p1" 2>&1) || fail "off: $out"
[ ! -e "$cfg" ] || fail "off left the config"
git -C "$work/p1" diff --quiet -- Cargo.lock || fail "off left Cargo.lock changed"
echo "$out" | grep -q 'removed' || fail "off does not say what it did: $out"
echo "$out" | grep -q 'Cargo.lock' || fail "off does not name Cargo.lock: $out"

# off with nothing to do says so; off with a foreign config refuses.
out=$("$off" "$work/p1" 2>&1) || fail "off twice: $out"
echo "$out" | grep -qi 'nothing' || fail "off twice does not say nothing to do: $out"
rc=0; out=$("$off" "$work/p5" 2>&1) || rc=$?
[ "$rc" = 1 ] || fail "off deleted a foreign config (exit $rc)"
[ -f "$work/p5/.cargo/config.toml" ] || fail "foreign config gone"

echo "ok   dev-local selftest"
