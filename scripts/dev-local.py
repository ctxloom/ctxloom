#!/usr/bin/env python3
"""Generate .cargo/config.toml: a [patch."<git url>"] per git source in Cargo.lock.

usage: dev-local.py [--project DIR] [ROOT]

Every package the lock takes from a git source is mapped to its path in the
sibling checkout of that repository (found under ROOT, default ~/workspace;
absolute paths, so an agent worktree works). The crate list and the URLs come
from Cargo.lock, never from a list kept here. The checkout of a repository is
DEV_LOCAL_<REPO> (the URL's last segment, upper-cased, - to _) if set, else
a checkout that holds every crate and is at the lock's rev (the build is then
the pinned one, with paths), else the first that holds every crate, with a
note; the usual places under ROOT before the worktrees:

    <seg>  <seg>/main  angzarr/<seg>  angzarr/<seg>/main  ctxloom/<seg>
    ctxloom/<seg>/main  (angzarr: angzarr/core/main)
    worktrees/<seg>--*  (angzarr also core--*, angzarr-core--*)

A checkout is used only if it holds every crate the lock takes from the
repository exactly once. If none does, each is listed with what it lacks, and
nothing is written. Nothing is overwritten that this script did not generate.
"""
import os
import subprocess
import sys
import tomllib

MARKER = "# generated by just dev-local"
SKIP = {"target", ".git", "worktrees", "node_modules", "mutants.out"}


def die(msg):
    print(f"dev-local: {msg}", file=sys.stderr)
    sys.exit(1)


def candidates(root, seg):
    """Checkout directories of a repository: the usual places, and the
    worktrees (a repository may have no primary checkout, or one on another
    branch than the lock's pin)."""
    rel = [f"{seg}", f"{seg}/main", f"angzarr/{seg}", f"angzarr/{seg}/main",
           f"ctxloom/{seg}", f"ctxloom/{seg}/main"]
    prefixes = [seg + "--"]
    if seg == "angzarr":
        rel = ["angzarr/core/main"] + rel
        prefixes += ["core--", "angzarr-core--"]
    out = [os.path.join(root, r) for r in rel]
    wt = os.path.join(root, "worktrees")
    trees = []
    if os.path.isdir(wt):
        trees = [os.path.join(wt, n) for n in sorted(os.listdir(wt))
                 if n.startswith(tuple(prefixes))]
    keep = lambda ds: [d for d in ds if os.path.isfile(os.path.join(d, "Cargo.toml"))]
    return keep(out), keep(trees)


def head(directory):
    return subprocess.run(["git", "-C", directory, "rev-parse", "HEAD"],
                          capture_output=True, text=True).stdout.strip()


def choose(root, seg, names, rev):
    """The checkout holding every crate of names (exactly once), preferring
    one whose HEAD is the lock's rev. Returns (directory, {name: path}, note)."""
    var = "DEV_LOCAL_" + seg.upper().replace("-", "_")
    given = os.environ.get(var)
    if given:
        if not os.path.isdir(given):
            die(f"{var}={given} is not a directory")
        groups = [[os.path.abspath(given)]]
    else:
        groups = [[os.path.abspath(d) for d in g] for g in candidates(root, seg)]
    if not any(groups):
        die(f"no checkout of {seg} under {root}; set {var} to its path")
    why, complete = [], []
    for cands in groups:  # the usual places, then the worktrees
        for d in cands:
            have = packages(d)
            bad = [n for n in sorted(names) if len(have.get(n, [])) != 1]
            if bad:
                why.append(f"{d}: " + ", ".join(
                    f"{n} ({len(have.get(n, []))} found)" for n in bad))
            else:
                complete.append((d, {n: have[n][0] for n in names}))
    for d, found in complete:  # at the lock's rev: the build is the pinned one
        if rev and head(d) == rev:
            return d, found, ""
    if complete:
        d, found = complete[0]
        note = f"{d} is at {head(d)[:8]}, not the lock's {rev[:8]}" if rev else ""
        return d, found, note
    die(f"no checkout of {seg} holds every crate the lock takes from it "
        f"(set {var} to one that does):\n  " + "\n  ".join(why))


def packages(directory):
    """package name -> [directories] of every Cargo.toml below directory."""
    found = {}
    for here, dirs, files in os.walk(directory):
        dirs[:] = [d for d in dirs if d not in SKIP]
        if "Cargo.toml" in files:
            try:
                with open(os.path.join(here, "Cargo.toml"), "rb") as f:
                    name = tomllib.load(f).get("package", {}).get("name")
            except (tomllib.TOMLDecodeError, OSError):
                name = None
            if name:
                found.setdefault(name, []).append(here)
    return found


def main():
    args = sys.argv[1:]
    project = os.getcwd()
    if args[:1] == ["--project"]:
        project, args = args[1], args[2:]
    root = os.path.abspath(os.path.expanduser(args[0] if args else "~/workspace"))
    cfg = os.path.join(project, ".cargo", "config.toml")
    if os.path.exists(cfg):
        with open(cfg) as f:
            first = f.readline().rstrip("\n")
        if first != MARKER:
            die(f"{cfg} was not generated by just dev-local; not overwriting it")
    with open(os.path.join(project, "Cargo.lock"), "rb") as f:
        lock = tomllib.load(f)
    by_url, revs = {}, {}
    for p in lock.get("package", []):
        src = p.get("source", "")
        if src.startswith("git+"):
            url = src[4:].split("?")[0].split("#")[0]
            by_url.setdefault(url, set()).add(p["name"])
            revs[url] = src.rsplit("#", 1)[-1] if "#" in src else ""
    if not by_url:
        die("Cargo.lock holds no git source; nothing to patch")
    lines = [MARKER, "# Path references to the sibling checkouts; gitignored, never committed.",
             "# `just dev-local-off` removes this and restores Cargo.lock.", ""]
    report = []
    for url in sorted(by_url):
        seg = url.rstrip("/").rsplit("/", 1)[-1].removesuffix(".git")
        _, found, note = choose(root, seg, by_url[url], revs[url])
        if note:
            report.append(f"note: {note}")
        lines.append(f'[patch."{url}"]')
        for name in sorted(found):
            lines.append(f'{name} = {{ path = "{found[name]}" }}')
            report.append(f"{name} -> {found[name]}")
        lines.append("")
    os.makedirs(os.path.dirname(cfg), exist_ok=True)
    with open(cfg, "w") as f:
        f.write("\n".join(lines))
    print("\n".join(report))
    print(f"dev-local: wrote {cfg} ({sum('->' in r for r in report)} crates); undo with `just dev-local-off`")


if __name__ == "__main__":
    main()
