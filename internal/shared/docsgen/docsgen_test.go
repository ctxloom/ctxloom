// filePrepender interpolates p.CLISource unguarded, so an unset
// field used to render an empty code span in the "generated from ... --help"
// banner instead of signalling the misconfiguration. Require CLISource
// non-empty before generating markdown.
func TestGenMarkdown_RequiresCLISource(t *testing.T) {
	p := fakeProduct()
	p.PrepareTree()
	p.CLISource = ""

	if err := GenMarkdown(p, t.TempDir()); err == nil {
		t.Fatal("expected an error generating markdown pages with an empty CLISource")
	}
}

func TestGenMan(t *testing.T) {
	dir := t.TempDir()
	p := fakeProduct()
	p.PrepareTree()

	stale := filepath.Join(dir, "widget-gone.1")
	if err := os.WriteFile(stale, []byte("stale"), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := GenMan(p, dir); err != nil {
		t.Fatalf("GenMan: %v", err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Error("stale man page not removed")
	}
	page, err := os.ReadFile(filepath.Join(dir, "widget-make.1"))
	if err != nil {
		t.Fatalf("expected a man page for `widget make`: %v", err)
	}
	if !strings.Contains(string(page), "WIDGET") {
		t.Errorf("man page missing the product title:\n%s", page)
	}
}

// TestGenManOnlyRemovesOwnPages guards the shared man/man1 directory: three
// products generate into it, so one product's regeneration must not delete
// another's pages.
func TestGenManOnlyRemovesOwnPages(t *testing.T) {
	dir := t.TempDir()
	other := filepath.Join(dir, "gadget-make.1")
	if err := os.WriteFile(other, []byte("another product"), 0o644); err != nil {
		t.Fatal(err)
	}

	p := fakeProduct()
	p.PrepareTree()
	if err := GenMan(p, dir); err != nil {
		t.Fatalf("GenMan: %v", err)
	}

	if _, err := os.Stat(other); err != nil {
		t.Errorf("another product's man page was removed: %v", err)
	}
}
