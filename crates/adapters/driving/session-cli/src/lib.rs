/// The `session` noun, shaped for mounting on the command line.
pub fn noun() -> Command {
    Session::augment_args(Command::new("session"))
        .about("Browse and manage your recorded sessions")
        .after_help("Examples:\n  ctxloom session list\n  ctxloom session search lockfile")
}

/// The `session` group.
#[derive(Args, Debug)]
pub struct Session {
    #[command(subcommand)]
    pub verb: Option<SessionVerb>,
}

#[derive(Subcommand, Debug)]
pub enum SessionVerb {
    /// List recorded sessions (default: current project; --all for everything)
    #[command(
        after_help = "Examples:\n  ctxloom session list\n  ctxloom session list --all\n  ctxloom session list --state live"
    )]
    List(ListArgs),
    /// Search sessions by name, title and times (default: current project; --all for everything)
    #[command(
        after_help = "Examples:\n  ctxloom session search lockfile migration\n  ctxloom session search --state ended lockfile"
    )]
    Search(SearchArgs),
    /// Show a named session: its title, state, engine and times
    #[command(after_help = "Examples:\n  ctxloom session show amber-swift-owl")]
    Show(HarpArgs),
    /// Set a recorded session's title; its name never changes
    #[command(
        after_help = "Examples:\n  ctxloom session rename amber-swift-owl \"the auth refactor\""
    )]
    Rename(RenameArgs),
    /// Keep a session's transcript at any age (--undo releases it)
    #[command(
        after_help = "Examples:\n  ctxloom session keep amber-swift-owl\n  ctxloom session keep amber-swift-owl --undo"
    )]
    Keep(KeepArgs),
    /// Destroy a session: every event of it and of its runs, its directory and its lock; its name stays taken
    #[cfg(feature = "purge")]
    #[command(
        after_help = "Examples:\n  ctxloom session remove amber-swift-owl\n  ctxloom session remove amber-swift-owl --yes\n  ctxloom session remove --older-than 90d --yes"
    )]
    Remove(RemoveArgs),
    /// Tidy every ended session of this project by rule: destroy what it can prove is safe, report the rest
    #[cfg(feature = "purge")]
    #[command(
        after_help = "Examples:\n  ctxloom session sweep\n  ctxloom session sweep --purge-older-than 90d --yes"
    )]
    Sweep(SweepArgs),
    /// The recorded conversation behind a session: list it, show it
    Transcript(Transcript),
    /// The scratch git checkouts a session left behind: list them, remove the safe ones
    Worktrees(Worktrees),
    /// Import Go ctxloom's sessions (~/.ctxloom/sessions) into each project's store, once
    #[command(after_help = "Examples:\n  ctxloom session import")]
    Import,
    /// Launch a child of a session: run by your daemon, kept open between tasks until it is closed
    #[command(
        after_help = "Examples:\n  ctxloom session launch amber-quiet-heron \"review the change\"\n  ctxloom session launch amber-quiet-heron --name brisk-copper-moth --agent reviewer"
    )]
    Launch(LaunchArgs),
    /// Send a session a message: inform (read at its next turn), wake (start a turn) or steer (interrupt its turn)
    #[command(
        after_help = "Examples:\n  ctxloom session send brisk-copper-moth wake \"now check the tests too\"\n  ctxloom session send brisk-copper-moth inform \"main moved\" --id m1"
    )]
    Send(SendArgs),
    /// Start a child's conversation again, in the same session
    #[command(after_help = "Examples:\n  ctxloom session clear brisk-copper-moth")]
    Clear(HarpArgs),
    /// Close a session for good: its engine ends, and so do the children it holds
    #[command(after_help = "Examples:\n  ctxloom session close brisk-copper-moth")]
    Close(HarpArgs),
    /// Stop a child's run: its engine exits, and the child stays open for its next message
    #[command(after_help = "Examples:\n  ctxloom session stop brisk-copper-moth")]
    Stop(HarpArgs),
    /// Restart a child's engine, resuming its conversation, once the turn in flight ends
    #[command(
        after_help = "Examples:\n  ctxloom session restart brisk-copper-moth\n  ctxloom session restart brisk-copper-moth --note \"the context changed\""
    )]
    Restart(RestartArgs),
    /// The permission asks waiting for you, from the sessions your daemon runs: list them, answer one
    #[command(
        after_help = "Examples:\n  ctxloom session approvals\n  ctxloom session approvals amber-quiet-heron\n  ctxloom session approvals answer ask-tidy-wren allow-once\n  ctxloom session approvals answer brisk-copper-moth deny \"not yet\""
    )]
    Approvals(Approvals),
}

/// The `session approvals` group: bare, the waiting asks listed.
#[derive(Args, Debug)]
#[command(args_conflicts_with_subcommands = true)]
pub struct Approvals {
    #[command(subcommand)]
    pub verb: Option<ApprovalsVerb>,
    /// Only the asks under this root session (default: every ask waiting in this project)
    #[arg(value_name = "SESSION-NAME")]
    pub harp: Option<String>,
}

#[derive(Subcommand, Debug)]
pub enum ApprovalsVerb {
    /// Answer an ask with one of the options it offers
    #[command(
        after_help = "Examples:\n  ctxloom session approvals answer ask-tidy-wren allow-once\n  ctxloom session approvals answer brisk-copper-moth allow-always --yes\n  ctxloom session approvals answer brisk-copper-moth deny \"not yet\""
    )]
    Answer(AnswerArgs),
}

#[derive(Args, Debug)]
pub struct AnswerArgs {
    /// The ask's name (ask-...), or the name of the session that asked, while one of its asks waits
    #[arg(value_name = "ASK-OR-SESSION")]
    pub target: String,
    /// One of the options the ask offers: allow-once, allow-session, allow-always, deny, deny-always
    #[arg(value_name = "OPTION")]
    pub option: String,
    /// Said to the engine with a deny (claude's asks only)
    #[arg(value_name = "MESSAGE")]
    pub message: Option<String>,
    /// Apply what this invocation shows (allow-always's config write), without asking
    #[arg(short = 'y', long)]
    pub yes: bool,
}

#[derive(Args, Debug)]
pub struct LaunchArgs {
    /// The owner session's name
    #[arg(value_name = "OWNER")]
    pub owner: String,
    /// The child's first task (default: none; it waits for its first message)
    #[arg(value_name = "TASK")]
    pub task: Option<String>,
    /// The child's name (default: one minted)
    #[arg(long, value_name = "SESSION-NAME")]
    pub name: Option<String>,
    /// The agent the child is planned for (default: the project's)
    #[arg(long, value_name = "AGENT")]
    pub agent: Option<String>,
    /// The child's engine (default: claude-code)
    #[arg(long, value_name = "ENGINE")]
    pub engine: Option<String>,
    /// The ctxloom project the child works in (default: the owner's); it must be one you trust
    #[arg(long, value_name = "DIR")]
    pub project: Option<String>,
}

/// How a message is acted on.
#[derive(clap::ValueEnum, Clone, Copy, Debug, PartialEq, Eq)]
pub enum UrgencyWord {
    /// Read at the session's next turn, whoever starts it
    Inform,
    /// Start a turn when the session is idle
    Wake,
    /// Interrupt the turn in flight, and run next
    Steer,
}

#[derive(Args, Debug)]
pub struct SendArgs {
    /// The session's name
    #[arg(value_name = "SESSION-NAME")]
    pub harp: String,
    /// How it is acted on: inform, wake or steer
    #[arg(value_name = "URGENCY", value_enum)]
    pub urgency: UrgencyWord,
    /// The message
    #[arg(value_name = "TEXT")]
    pub text: String,
    /// The message's id: the same id sent again is one message (default: one minted)
    #[arg(long, value_name = "ID")]
    pub id: Option<String>,
}

#[derive(Args, Debug, Default)]
pub struct ListArgs {
    /// Include sessions from every project (default: filter to the current one)
    #[arg(long)]
    pub all: bool,
    /// Only sessions in this state, from the session's liveness lock: live, ended, unknown
    #[arg(long, value_name = "STATE")]
    pub state: Option<String>,
}

#[derive(Args, Debug)]
pub struct SearchArgs {
    /// Words that must all match, case-insensitively, the session's name, title or times
    #[arg(required = true, value_name = "WORD")]
    pub words: Vec<String>,
    /// Search sessions from every project (default: the current one)
    #[arg(long)]
    pub all: bool,
    /// Only sessions in this state, from the session's liveness lock: live, ended, unknown
    #[arg(long, value_name = "STATE")]
    pub state: Option<String>,
}

#[derive(Args, Debug)]
pub struct HarpArgs {
    /// The session's name
    #[arg(value_name = "SESSION-NAME")]
    pub harp: String,
}

#[derive(Args, Debug)]
pub struct RestartArgs {
    /// The session's name
    #[arg(value_name = "SESSION-NAME")]
    pub harp: String,
    /// Why, in your words (recorded with the restart)
    #[arg(long, value_name = "TEXT", default_value = "")]
    pub note: String,
}

#[derive(Args, Debug)]
pub struct RenameArgs {
    /// The session's name
    #[arg(value_name = "SESSION-NAME")]
    pub harp: String,
    /// The title, free text (empty clears it)
    #[arg(value_name = "TITLE")]
    pub title: String,
}

#[derive(Args, Debug)]
pub struct KeepArgs {
    /// The session's name
    #[arg(value_name = "SESSION-NAME")]
    pub harp: String,
    /// Release the mark: the transcript becomes reclaimable once its retention has passed
    #[arg(long)]
    pub undo: bool,
}

/// One session by its name, or every ended session of this project last
/// active before an age (the age form is `session sweep`'s, with that age).
#[cfg(feature = "purge")]
#[derive(Args, Debug)]
#[command(group = clap::ArgGroup::new("which").required(true).args(["harp", "older_than"]))]
pub struct RemoveArgs {
    /// The session's name
    #[arg(value_name = "SESSION-NAME")]
    pub harp: Option<String>,
    /// Instead of one session, every ended session of this project last active before this age (90d, 12w, 720h) or date (2026-01-01), each decided as `session sweep` decides it
    #[arg(long, value_name = "AGE", conflicts_with_all = ["harp", "even_if_live"])]
    pub older_than: Option<String>,
    /// Apply the plan this invocation printed (default: report only)
    #[arg(short = 'y', long)]
    pub yes: bool,
    /// Permit destroying a session whose owner may still be running: its lock is held, or it has none
    #[arg(long)]
    pub even_if_live: bool,
}

/// The `session transcript` group.
